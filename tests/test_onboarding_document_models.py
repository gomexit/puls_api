def test_ddl_oracle_identifier_lengths():
    names = re.findall(r"CONSTRAINT\s+([A-Z0-9_]+)", SQL_NO_COMMENTS)
    names += re.findall(r"CREATE\s+INDEX\s+([A-Z0-9_]+)", SQL_NO_COMMENTS)
    assert len(names) >= 8
    for name in names:
        assert len(name) <= 30, f"{name} ima {len(name)} karaktera"


def test_ddl_has_no_destructive_or_seed_statements():
    for forbidden in ("DROP ", "DELETE ", "TRUNCATE ", "ALTER ", "INSERT ", "UPDATE ", "MERGE "):
        assert forbidden not in SQL_NO_COMMENTS, forbidden


def test_ddl_only_creates_the_new_table_and_index():
    creates = re.findall(r"CREATE\s+(\w+)\s+(?:UNIQUE\s+)?(\w+)", SQL_NO_COMMENTS)
    assert creates == [("TABLE", "PULS_ONBOARDING_DOKUMENTI"), ("INDEX", "IX_ONB_DOK_STATUS_RED")]
