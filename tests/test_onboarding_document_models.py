"""DDL (sql/009_onboarding_documents_module.sql) i ORM model PULS_ONBOARDING_DOKUMENTI."""

import re
from pathlib import Path

from sqlalchemy import BLOB, CHAR
from sqlalchemy.dialects import oracle
from sqlalchemy.dialects.oracle import NCLOB, NVARCHAR2
from sqlalchemy.schema import CreateTable

from app.models.onboarding_dokument import (
    ONB_DOKUMENT_STATUS_ARCHIVED,
    ONB_DOKUMENT_STATUS_DRAFT,
    ONB_DOKUMENT_STATUS_PUBLISHED,
    OnboardingDokument,
    is_valid_onboarding_document_transition,
)

SQL_PATH = Path(__file__).resolve().parent.parent / "sql" / "009_onboarding_documents_module.sql"
SQL = SQL_PATH.read_text(encoding="utf-8")
SQL_NO_COMMENTS = "\n".join(
    line.split("--", 1)[0] for line in SQL.splitlines()
).upper()


def _col(name: str):
    return OnboardingDokument.__table__.c[name]


# ----------------------------------------------------------------------- model
def test_table_name():
    assert OnboardingDokument.__tablename__ == "PULS_ONBOARDING_DOKUMENTI"


def test_oracle_types():
    assert isinstance(_col("NAZIV").type, NVARCHAR2)
    assert _col("NAZIV").type.length == 200
    assert isinstance(_col("ORIGINALNI_NAZIV_FAJLA").type, NVARCHAR2)
    assert _col("ORIGINALNI_NAZIV_FAJLA").type.length == 255
    assert isinstance(_col("OPIS").type, NCLOB)
    assert isinstance(_col("SADRZAJ").type, BLOB)
    assert isinstance(_col("SHA256").type, CHAR)
    assert _col("SHA256").type.length == 64
    for name in ("DATUM_KREIRANJA", "DATUM_IZMENE", "DATUM_OBJAVE"):
        assert _col(name).type.timezone is False


def test_blob_column_is_deferred():
    # SADRZAJ se nikad ne ucitava implicitno (lista/detalj/FOR UPDATE).
    prop = OnboardingDokument.__mapper__.get_property("sadrzaj")
    assert prop.deferred is True


def test_model_compiles_for_oracle():
    ddl = str(CreateTable(OnboardingDokument.__table__).compile(dialect=oracle.dialect()))
    assert "BLOB" in ddl.upper()
    assert "NCLOB" in ddl.upper()
    assert "NVARCHAR2" in ddl.upper()


def test_status_transitions_table():
    D, P, A = ONB_DOKUMENT_STATUS_DRAFT, ONB_DOKUMENT_STATUS_PUBLISHED, ONB_DOKUMENT_STATUS_ARCHIVED
    allowed = {(D, P), (D, A), (P, D), (P, A)}
    for a in (D, P, A):
        for b in (D, P, A):
            assert is_valid_onboarding_document_transition(a, b) == ((a, b) in allowed)


