-- ============================================================================
-- 012_igra_module.sql - modul GOMEX PUTANJA (dnevna logicka igra)
--
-- Preduslov: sql/010_osnova_module.sql (kljuc MODUL_IGRA, AKCIJA_TIP 'GAME').
-- Skripta je aditivna: samo nove tabele i indeksi, bez izmena postojecih objekata.
--
-- Tabele:
--   1) PULS_IGRA_NIVOI     - jedan nivo po danu; pravi ga server sam (generator),
--                            pri prvom pokretanju igre tog dana
--   2) PULS_IGRA_REZULTATI - jedan red po zaposlenom i danu; racuna se prvo resenje
--
-- Modul se ukljucuje parametrom MODUL_IGRA (ISKLJUCEN / PILOT / SVI). Dok je
-- ISKLJUCEN, API ne cita ove tabele.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1) PULS_IGRA_NIVOI
-- PODACI: JSON sa tablom koju dobija aplikacija (velicina, tacke redom, zidovi).
-- RESENJE: JSON sa jednom ispravnom putanjom; nikad se ne salje aplikaciji.
-- Server prihvata svaku ispravnu putanju, ne samo ovu.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_IGRA_NIVOI (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    DATUM                   DATE            NOT NULL,
    VELICINA                NUMBER(2,0)     NOT NULL,
    PODACI                  CLOB            NOT NULL,
    RESENJE                 CLOB            NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_IGRA_NIVOI PRIMARY KEY (ID),
    CONSTRAINT UQ_IGRA_NIVO_DATUM UNIQUE (DATUM),
    CONSTRAINT CK_IGRA_NIVO_VELICINA CHECK (VELICINA BETWEEN 4 AND 10)
)
TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 2) PULS_IGRA_REZULTATI
-- U_TOKU: igra je pokrenuta; svako novo pokretanje pre resenja pomera DATUM_POCETKA.
-- RESEN:  prvo ispravno resenje; vreme (TRAJANJE_MS) meri server i vise se ne menja.
-- ORGJED_SIFRA je snimak primarne org. jedinice pri prvom pokretanju (prosek prodavnice).
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_IGRA_REZULTATI (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    NIVO_ID                 NUMBER(19,0)    NOT NULL,
    KORISNIK_ID             NUMBER(19,0)    NOT NULL,
    ORGJED_SIFRA            VARCHAR2(50),
    STATUS                  VARCHAR2(20)    DEFAULT 'U_TOKU' NOT NULL,
    DATUM_POCETKA           TIMESTAMP(6)    NOT NULL,
    DATUM_RESENJA           TIMESTAMP(6),
    TRAJANJE_MS             NUMBER(10,0),
    BROJ_POKRETANJA         NUMBER(5,0)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PULS_IGRA_REZULTATI PRIMARY KEY (ID),
    CONSTRAINT FK_IGRA_REZ_NIVO FOREIGN KEY (NIVO_ID) REFERENCES PULS_IGRA_NIVOI (ID),
    CONSTRAINT FK_IGRA_REZ_KORISNIK FOREIGN KEY (KORISNIK_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT CK_IGRA_REZ_STATUS CHECK (STATUS IN ('U_TOKU', 'RESEN')),
    CONSTRAINT UQ_IGRA_REZ_KORISNIK UNIQUE (NIVO_ID, KORISNIK_ID)
)
TABLESPACE GOMEX;

-- Prosek prodavnice za dan.
CREATE INDEX IX_IGRA_REZ_ORGJED
    ON PULS_IGRA_REZULTATI (NIVO_ID, ORGJED_SIFRA, STATUS)
    TABLESPACE GOMEX;

-- Niz dana zaredom (resenja jednog zaposlenog).
CREATE INDEX IX_IGRA_REZ_KORISNIK
    ON PULS_IGRA_REZULTATI (KORISNIK_ID, STATUS)
    TABLESPACE GOMEX;

COMMIT;
