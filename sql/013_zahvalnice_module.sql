-- Preduslov: sql/010_osnova_module.sql (kljuc MODUL_ZAHVALNICE, AKCIJA_TIP 'KUDOS',
-- TIP_DOGADJAJA 'KUDOS_RECEIVED').
-- Skripta je aditivna: samo nove tabele i indeksi, bez izmena postojecih objekata.
--
-- Tabele:
--   1) PULS_ZAHVALNICE         - jedna zahvalnica (objavljuje se odmah, bez odobrenja)
--   2) PULS_ZAHVALNICA_PRIJAVE - prijave neprimerenih zahvalnica (jedna po zaposlenom)
--
-- Modul se ukljucuje parametrom MODUL_ZAHVALNICE (ISKLJUCEN / PILOT / SVI). Dok je
-- ISKLJUCEN, API ne cita ove tabele.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1) PULS_ZAHVALNICE
-- STATUS: OBJAVLJENA (vidljiva), NA_PROVERI (3 prijave - sklonjena dok je HR ne
--         pogleda), SAKRIVENA (HR je sklonio).
-- PROVERENA = 'D': HR je pregledao i vratio zahvalnicu; nove prijave je vise ne sklanjaju.
-- *_ORGJED: snimak primarne org. jedinice u trenutku slanja (filter "moja prodavnica").
-- PROCITANA: primalac je otvorio "Moje zahvalnice" (bedz na pocetnom ekranu).
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ZAHVALNICE (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    POSILJALAC_ID           NUMBER(19,0)    NOT NULL,
    PRIMALAC_ID             NUMBER(19,0)    NOT NULL,
    POSILJALAC_ORGJED       VARCHAR2(50),
    PRIMALAC_ORGJED         VARCHAR2(50),
    POVOD                   VARCHAR2(20)    NOT NULL,
    TEKST                   NVARCHAR2(280)  NOT NULL,
    STATUS                  VARCHAR2(20)    DEFAULT 'OBJAVLJENA' NOT NULL,
    PROVERENA               CHAR(1)         DEFAULT 'N' NOT NULL,
    PROCITANA               CHAR(1)         DEFAULT 'N' NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE            TIMESTAMP(6),
    IZMENIO_KORISNIK_ID     NUMBER(19,0),
    CONSTRAINT PK_PULS_ZAHVALNICE PRIMARY KEY (ID),
    CONSTRAINT FK_ZAHV_POSILJALAC FOREIGN KEY (POSILJALAC_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT FK_ZAHV_PRIMALAC FOREIGN KEY (PRIMALAC_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT CK_ZAHV_POVOD CHECK (POVOD IN ('POMOC', 'TIMSKI_RAD', 'LJUBAZNOST')),
    CONSTRAINT CK_ZAHV_STATUS CHECK (STATUS IN ('OBJAVLJENA', 'NA_PROVERI', 'SAKRIVENA')),
    CONSTRAINT CK_ZAHV_PROVERENA CHECK (PROVERENA IN ('D', 'N')),
    CONSTRAINT CK_ZAHV_PROCITANA CHECK (PROCITANA IN ('D', 'N')),
    CONSTRAINT CK_ZAHV_NE_SEBI CHECK (POSILJALAC_ID <> PRIMALAC_ID)
)
TABLESPACE GOMEX;

-- Lista "svi" i admin lista po statusu (najnovije prvo).
CREATE INDEX IX_ZAHV_STATUS_DATUM
    ON PULS_ZAHVALNICE (STATUS, DATUM_KREIRANJA)
    TABLESPACE GOMEX;

-- Primljene (i bedz neprocitanih).
CREATE INDEX IX_ZAHV_PRIMALAC
    ON PULS_ZAHVALNICE (PRIMALAC_ID, STATUS, PROCITANA)
    TABLESPACE GOMEX;

-- Poslate i dnevno ogranicenje slanja.
CREATE INDEX IX_ZAHV_POSILJALAC
    ON PULS_ZAHVALNICE (POSILJALAC_ID, DATUM_KREIRANJA)
    TABLESPACE GOMEX;

-- Lista "moja prodavnica".
CREATE INDEX IX_ZAHV_PRIMALAC_ORGJED
    ON PULS_ZAHVALNICE (PRIMALAC_ORGJED, STATUS)
    TABLESPACE GOMEX;

CREATE INDEX IX_ZAHV_POSILJALAC_ORGJED
    ON PULS_ZAHVALNICE (POSILJALAC_ORGJED, STATUS)
    TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 2) PULS_ZAHVALNICA_PRIJAVE
-- Jedan zaposleni prijavljuje jednu zahvalnicu najvise jednom.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ZAHVALNICA_PRIJAVE (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    ZAHVALNICA_ID           NUMBER(19,0)    NOT NULL,
    KORISNIK_ID             NUMBER(19,0)    NOT NULL,
    RAZLOG                  NVARCHAR2(200),
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_ZAHVALNICA_PRIJAVE PRIMARY KEY (ID),
    CONSTRAINT FK_ZAHV_PRIJ_ZAHVALNICA FOREIGN KEY (ZAHVALNICA_ID) REFERENCES PULS_ZAHVALNICE (ID),
    CONSTRAINT FK_ZAHV_PRIJ_KORISNIK FOREIGN KEY (KORISNIK_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT UQ_ZAHV_PRIJAVA UNIQUE (ZAHVALNICA_ID, KORISNIK_ID)
)
TABLESPACE GOMEX;

COMMIT;
