-- ============================================================================
-- PULS - Modul PULS IZAZOV (nedeljni kviz)
--
-- SHEMA: PORTAL           TABLESPACE: GOMEX           ORACLE: 19c
--
-- !!! VAZNO !!!
-- Ova skripta se NE izvrsava automatski iz aplikacije. Mora se RUCNO pregledati
-- i pokrenuti (SQL Developer / SQL*Plus) tek nakon nezavisnog pregleda.
-- Preduslov: sql/010_osnova_module.sql (PULS_SLIKE, AKCIJA_TIP 'QUIZ',
-- TIP_DOGADJAJA 'QUIZ_ACTIVATED'/'QUIZ_EXPIRING', kljuc MODUL_KVIZ).
--
-- Sadrzaj:
--   1) PULS_KVIZ_KATEGORIJE  - sifarnik kategorija pitanja (uredjuje se u portalu)
--   2) PULS_KVIZOVI          - kviz (period, trajanje, status)
--   3) PULS_KVIZ_CILJEVI     - ciljanje (bez redova = svi zaposleni)
--   4) PULS_KVIZ_PITANJA     - pitanja kviza
--   5) PULS_KVIZ_OPCIJE      - ponudjeni odgovori (tacno jedan je tacan)
--   6) PULS_KVIZ_POKUSAJI    - jedan pokusaj po zaposlenom i kvizu
--   7) PULS_KVIZ_ODGOVORI    - odgovor na jedno pitanje u pokusaju
--
-- Charset: NLS_CHARACTERSET = EE8ISO8859P2, pa korisnicki tekst ide u NVARCHAR2.
-- Skripta NE sadrzi: DROP / DELETE / TRUNCATE / ALTER postojecih tabela.
-- HR izvori se ne citaju.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1) PULS_KVIZ_KATEGORIJE - sifarnik kategorija pitanja
-- Kategorije se dodaju i menjaju kroz portal. Brisanja nema: neaktivna kategorija
-- ostaje na postojecim pitanjima, ali se ne nudi za nova.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_KVIZ_KATEGORIJE (
    SIFRA                   VARCHAR2(30)    NOT NULL,
    NAZIV                   NVARCHAR2(100)  NOT NULL,
    REDOSLED                NUMBER(5,0)     DEFAULT 0 NOT NULL,
    AKTIVNA                 CHAR(1)         DEFAULT 'D' NOT NULL,
    KREIRAO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    IZMENIO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE            TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_KVIZ_KATEGORIJE PRIMARY KEY (SIFRA),
    CONSTRAINT CK_KVIZ_KAT_AKTIVNA CHECK (AKTIVNA IN ('D', 'N')),
    CONSTRAINT CK_KVIZ_KAT_SIFRA CHECK (REGEXP_LIKE(SIFRA, '^[A-Z0-9_]{1,30}$'))
)
TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 2) PULS_KVIZOVI
-- DRAFT -> OBJAVLJEN -> ARHIVIRAN. Objavljen kviz je dostupan od DATUM_OD do
-- DATUM_DO. Posle objave se pitanja ne menjaju (samo naziv, opis i produzenje
-- roka). Backend ne dozvoljava preklapanje perioda dva objavljena kviza.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_KVIZOVI (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    NAZIV                   NVARCHAR2(200)  NOT NULL,
    OPIS                    NVARCHAR2(1000),
    DATUM_OD                TIMESTAMP(6)    NOT NULL,
    DATUM_DO                TIMESTAMP(6)    NOT NULL,
    TRAJANJE_SEKUNDI        NUMBER(5,0)     DEFAULT 120 NOT NULL,
    STATUS                  VARCHAR2(20)    DEFAULT 'DRAFT' NOT NULL,
    KREIRAO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    IZMENIO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    DATUM_OBJAVE            TIMESTAMP(6),
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE            TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_KVIZOVI PRIMARY KEY (ID),
    CONSTRAINT CK_KVIZ_STATUS CHECK (STATUS IN ('DRAFT', 'OBJAVLJEN', 'ARHIVIRAN')),
    CONSTRAINT CK_KVIZ_PERIOD CHECK (DATUM_DO > DATUM_OD),
    CONSTRAINT CK_KVIZ_TRAJANJE CHECK (TRAJANJE_SEKUNDI BETWEEN 30 AND 900)
)
TABLESPACE GOMEX;

CREATE INDEX IX_KVIZOVI_STATUS_PERIOD
    ON PULS_KVIZOVI (STATUS, DATUM_OD, DATUM_DO)
    TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 3) PULS_KVIZ_CILJEVI - kome je kviz namenjen
-- Bez redova: svi zaposleni (kojima je modul KVIZ ukljucen).
-- ORGJED: aktivan raspored u org. jedinici; PLATNI_BROJ: konkretan zaposleni.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_KVIZ_CILJEVI (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    KVIZ_ID                 NUMBER(19,0)    NOT NULL,
    TIP_CILJA               VARCHAR2(20)    NOT NULL,
    VREDNOST                VARCHAR2(50)    NOT NULL,
    CONSTRAINT PK_PULS_KVIZ_CILJEVI PRIMARY KEY (ID),
    CONSTRAINT FK_KVIZ_CILJ_KVIZ FOREIGN KEY (KVIZ_ID) REFERENCES PULS_KVIZOVI (ID),
    CONSTRAINT CK_KVIZ_CILJ_TIP CHECK (TIP_CILJA IN ('ORGJED', 'PLATNI_BROJ')),
    CONSTRAINT UQ_KVIZ_CILJ UNIQUE (KVIZ_ID, TIP_CILJA, VREDNOST)
)
TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 4) PULS_KVIZ_PITANJA
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_KVIZ_PITANJA (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    KVIZ_ID                 NUMBER(19,0)    NOT NULL,
    REDOSLED                NUMBER(3,0)     NOT NULL,
    TEKST                   NVARCHAR2(500)  NOT NULL,
    KATEGORIJA_SIFRA        VARCHAR2(30)    NOT NULL,
    SLIKA_ID                NUMBER(19,0),
    OBJASNJENJE             NVARCHAR2(500)  NOT NULL,
    CONSTRAINT PK_PULS_KVIZ_PITANJA PRIMARY KEY (ID),
    CONSTRAINT FK_KVIZ_PIT_KVIZ FOREIGN KEY (KVIZ_ID) REFERENCES PULS_KVIZOVI (ID),
    CONSTRAINT FK_KVIZ_PIT_KAT FOREIGN KEY (KATEGORIJA_SIFRA) REFERENCES PULS_KVIZ_KATEGORIJE (SIFRA),
    CONSTRAINT FK_KVIZ_PIT_SLIKA FOREIGN KEY (SLIKA_ID) REFERENCES PULS_SLIKE (ID),
    CONSTRAINT UQ_KVIZ_PIT_REDOSLED UNIQUE (KVIZ_ID, REDOSLED)
)
TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 5) PULS_KVIZ_OPCIJE - ponudjeni odgovori; backend proverava da je tacno jedan tacan
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_KVIZ_OPCIJE (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    PITANJE_ID              NUMBER(19,0)    NOT NULL,
    REDOSLED                NUMBER(3,0)     NOT NULL,
    TEKST                   NVARCHAR2(200)  NOT NULL,
    TACNA                   CHAR(1)         DEFAULT 'N' NOT NULL,
    CONSTRAINT PK_PULS_KVIZ_OPCIJE PRIMARY KEY (ID),
    CONSTRAINT FK_KVIZ_OPC_PITANJE FOREIGN KEY (PITANJE_ID) REFERENCES PULS_KVIZ_PITANJA (ID),
    CONSTRAINT CK_KVIZ_OPC_TACNA CHECK (TACNA IN ('D', 'N')),
    CONSTRAINT UQ_KVIZ_OPC_REDOSLED UNIQUE (PITANJE_ID, REDOSLED)
)
TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 6) PULS_KVIZ_POKUSAJI - jedan pokusaj po zaposlenom i kvizu
-- ORGJED_SIFRA je snimak primarne org. jedinice u trenutku pocetka (prosek
-- prodavnice ostaje tacan i posle premestaja zaposlenog).
-- Vreme meri server: DATUM_POCETKA + TRAJANJE_SEKUNDI kviza je rok.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_KVIZ_POKUSAJI (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    KVIZ_ID                 NUMBER(19,0)    NOT NULL,
    KORISNIK_ID             NUMBER(19,0)    NOT NULL,
    ORGJED_SIFRA            VARCHAR2(50),
    STATUS                  VARCHAR2(20)    DEFAULT 'U_TOKU' NOT NULL,
    DATUM_POCETKA           TIMESTAMP(6)    NOT NULL,
    DATUM_ZAVRSETKA         TIMESTAMP(6),
    BROJ_TACNIH             NUMBER(3,0)     DEFAULT 0 NOT NULL,
    TRAJANJE_MS             NUMBER(10,0),
    CONSTRAINT PK_PULS_KVIZ_POKUSAJI PRIMARY KEY (ID),
    CONSTRAINT FK_KVIZ_POK_KVIZ FOREIGN KEY (KVIZ_ID) REFERENCES PULS_KVIZOVI (ID),
    CONSTRAINT FK_KVIZ_POK_KORISNIK FOREIGN KEY (KORISNIK_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT CK_KVIZ_POK_STATUS CHECK (STATUS IN ('U_TOKU', 'ZAVRSEN')),
    CONSTRAINT UQ_KVIZ_POK_KORISNIK UNIQUE (KVIZ_ID, KORISNIK_ID)
)
TABLESPACE GOMEX;

-- Prosek org. jedinice i rezultati po org. jedinici.
CREATE INDEX IX_KVIZ_POK_ORGJED
    ON PULS_KVIZ_POKUSAJI (KVIZ_ID, ORGJED_SIFRA, STATUS)
    TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 7) PULS_KVIZ_ODGOVORI - jedan odgovor po pitanju u pokusaju
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_KVIZ_ODGOVORI (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    POKUSAJ_ID              NUMBER(19,0)    NOT NULL,
    PITANJE_ID              NUMBER(19,0)    NOT NULL,
    OPCIJA_ID               NUMBER(19,0)    NOT NULL,
    TACAN                   CHAR(1)         NOT NULL,
    DATUM_ODGOVORA          TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_KVIZ_ODGOVORI PRIMARY KEY (ID),
    CONSTRAINT FK_KVIZ_ODG_POKUSAJ FOREIGN KEY (POKUSAJ_ID) REFERENCES PULS_KVIZ_POKUSAJI (ID),
    CONSTRAINT FK_KVIZ_ODG_PITANJE FOREIGN KEY (PITANJE_ID) REFERENCES PULS_KVIZ_PITANJA (ID),
    CONSTRAINT FK_KVIZ_ODG_OPCIJA FOREIGN KEY (OPCIJA_ID) REFERENCES PULS_KVIZ_OPCIJE (ID),
    CONSTRAINT CK_KVIZ_ODG_TACAN CHECK (TACAN IN ('D', 'N')),
    CONSTRAINT UQ_KVIZ_ODG_PITANJE UNIQUE (POKUSAJ_ID, PITANJE_ID)
)
TABLESPACE GOMEX;

-- Statistika po pitanju.
CREATE INDEX IX_KVIZ_ODG_PITANJE
    ON PULS_KVIZ_ODGOVORI (PITANJE_ID, TACAN)
    TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 8) Pocetne kategorije (samo ako ne postoje; menjaju se kroz portal)
-- ----------------------------------------------------------------------------
MERGE INTO PULS_KVIZ_KATEGORIJE k
USING (SELECT 'ASORTIMAN' AS SIFRA, 'Asortiman' AS NAZIV, 10 AS REDOSLED FROM DUAL
       UNION ALL SELECT 'AKCIJE', 'Akcije', 20 FROM DUAL
       UNION ALL SELECT 'ISTORIJA', 'Istorija kompanije', 30 FROM DUAL
       UNION ALL SELECT 'OPSTE', 'Opšte', 40 FROM DUAL) src
   ON (k.SIFRA = src.SIFRA)
WHEN NOT MATCHED THEN
    INSERT (SIFRA, NAZIV, REDOSLED, AKTIVNA, KREIRAO_PLATNI_BROJ, IZMENIO_PLATNI_BROJ)
    VALUES (src.SIFRA, src.NAZIV, src.REDOSLED, 'D', 'SISTEM', 'SISTEM');

COMMIT;
