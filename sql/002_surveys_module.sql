-- !!! VAZNO !!!
-- Ova skripta se NE izvrsava automatski. Mora se RUCNO pregledati i pokrenuti
-- (SQL Developer / SQL*Plus) tek nakon nezavisnog pregleda.
--
-- Charset (potvrdjeno read-only pre-flight proverom):
--   NLS_CHARACTERSET       = EE8ISO8859P2  (NE cuva cirilicu/emoji u VARCHAR2!)
--   NLS_NCHAR_CHARACTERSET = AL16UTF16
-- Zato korisnicki tekst ide u NVARCHAR2 / NCLOB, a kontrolisani kodovi/statusi/
-- platni broj / org. sifre ostaju VARCHAR2.
--
-- Konvencije (kao ostale PULS tabele):
--   ID       NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY
--   boolean  CHAR(1) 'D'/'N'
--   vreme    TIMESTAMP(6), DATUM_KREIRANJA DEFAULT SYSTIMESTAMP
--
-- Skripta NE sadrzi: DROP / DELETE / TRUNCATE / destruktivni ALTER / testne
-- podatke / izmene postojecih tabela. Tipovi anketa se NE seed-uju ovde -
-- odrzavaju se kroz admin API.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1) PULS_ANKETA_TIPOVI - konfiguracioni tipovi anketa (odrzavaju se kroz admin API)
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_TIPOVI (
    SIFRA             VARCHAR2(50)   NOT NULL,
    NAZIV             NVARCHAR2(200) NOT NULL,
    AKTIVAN           CHAR(1)        DEFAULT 'D' NOT NULL,
    DATUM_KREIRANJA   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE      TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANKETA_TIPOVI PRIMARY KEY (SIFRA),
    CONSTRAINT CK_ANK_TIP_AKTIVAN CHECK (AKTIVAN IN ('D', 'N'))
);


-- ----------------------------------------------------------------------------
-- 2) PULS_ANKETE - osnovni podaci ankete
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETE (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    TIP_SIFRA         VARCHAR2(50)   NOT NULL,
    NAZIV             NVARCHAR2(200) NOT NULL,
    OPIS              NCLOB,
    ANONIMNA          CHAR(1)        DEFAULT 'N' NOT NULL,
    STATUS            VARCHAR2(20)   DEFAULT 'DRAFT' NOT NULL,
    DATUM_POCETKA     TIMESTAMP(6)   NOT NULL,
    DATUM_ZAVRSETKA   TIMESTAMP(6)   NOT NULL,
    DATUM_KREIRANJA   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE      TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANKETE PRIMARY KEY (ID),
    CONSTRAINT FK_ANKETE_TIP FOREIGN KEY (TIP_SIFRA) REFERENCES PULS_ANKETA_TIPOVI (SIFRA),
    CONSTRAINT CK_ANKETE_ANONIMNA CHECK (ANONIMNA IN ('D', 'N')),
    CONSTRAINT CK_ANKETE_STATUS
        CHECK (STATUS IN ('DRAFT', 'SCHEDULED', 'ACTIVE', 'CLOSED', 'ARCHIVED')),
    CONSTRAINT CK_ANKETE_DATUMI CHECK (DATUM_ZAVRSETKA > DATUM_POCETKA)
);
CREATE INDEX IX_ANKETE_TIP ON PULS_ANKETE (TIP_SIFRA);
CREATE INDEX IX_ANKETE_STATUS ON PULS_ANKETE (STATUS);


-- ----------------------------------------------------------------------------
-- 3) PULS_ANKETA_SEKCIJE
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_SEKCIJE (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    ANKETA_ID         NUMBER(19,0)   NOT NULL,
    NAZIV             NVARCHAR2(200) NOT NULL,
    REDOSLED          NUMBER(10,0)   NOT NULL,
    DATUM_KREIRANJA   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE      TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANKETA_SEKCIJE PRIMARY KEY (ID),
    CONSTRAINT FK_SEKCIJE_ANKETA FOREIGN KEY (ANKETA_ID) REFERENCES PULS_ANKETE (ID),
    CONSTRAINT CK_SEKCIJE_REDOSLED CHECK (REDOSLED > 0),
    CONSTRAINT UX_SEKCIJE_REDOSLED UNIQUE (ANKETA_ID, REDOSLED)
);
CREATE INDEX IX_SEKCIJE_ANKETA ON PULS_ANKETA_SEKCIJE (ANKETA_ID);


-- ----------------------------------------------------------------------------
-- 4) PULS_ANKETA_PITANJA
--    USLOV_PITANJE_ID/USLOV_OPERATOR opisuju kada je OVO (zavisno) pitanje vidljivo.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_PITANJA (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    SEKCIJA_ID        NUMBER(19,0)   NOT NULL,
    TEKST             NCLOB          NOT NULL,
    TIP_PITANJA       VARCHAR2(20)   NOT NULL,
    OBAVEZNO          CHAR(1)        DEFAULT 'N' NOT NULL,
    REDOSLED          NUMBER(10,0)   NOT NULL,
    USLOV_PITANJE_ID  NUMBER(19,0),
    USLOV_OPERATOR    VARCHAR2(20),
    DATUM_KREIRANJA   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE      TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANKETA_PITANJA PRIMARY KEY (ID),
    CONSTRAINT FK_PITANJA_SEKCIJA FOREIGN KEY (SEKCIJA_ID) REFERENCES PULS_ANKETA_SEKCIJE (ID),
    CONSTRAINT FK_PITANJA_USLOV FOREIGN KEY (USLOV_PITANJE_ID) REFERENCES PULS_ANKETA_PITANJA (ID),
    CONSTRAINT CK_PITANJA_OBAVEZNO CHECK (OBAVEZNO IN ('D', 'N')),
    CONSTRAINT CK_PITANJA_REDOSLED CHECK (REDOSLED > 0),
    CONSTRAINT CK_PITANJA_TIP CHECK (TIP_PITANJA IN
        ('SINGLE_CHOICE', 'MULTI_CHOICE', 'TEXT', 'RATING_1_5', 'RATING_1_10', 'BOOLEAN', 'DROPDOWN')),
    CONSTRAINT CK_PITANJA_USLOV_OPERATOR
        CHECK (USLOV_OPERATOR IS NULL OR USLOV_OPERATOR IN ('EQUALS', 'NOT_EQUALS', 'IN')),
    -- Uslov je ili potpuno prisutan ili potpuno odsutan.
    CONSTRAINT CK_PITANJA_USLOV_PAR CHECK (
        (USLOV_PITANJE_ID IS NULL AND USLOV_OPERATOR IS NULL) OR
        (USLOV_PITANJE_ID IS NOT NULL AND USLOV_OPERATOR IS NOT NULL)),
    -- Pitanje ne moze zavisiti od samog sebe.
    CONSTRAINT CK_PITANJA_NE_SAM CHECK (USLOV_PITANJE_ID IS NULL OR USLOV_PITANJE_ID <> ID),
    CONSTRAINT UX_PITANJA_REDOSLED UNIQUE (SEKCIJA_ID, REDOSLED)
);
CREATE INDEX IX_PITANJA_SEKCIJA ON PULS_ANKETA_PITANJA (SEKCIJA_ID);
CREATE INDEX IX_PITANJA_USLOV ON PULS_ANKETA_PITANJA (USLOV_PITANJE_ID);


-- ----------------------------------------------------------------------------
-- 5) PULS_ANKETA_OPCIJE
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_OPCIJE (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    PITANJE_ID        NUMBER(19,0)   NOT NULL,
    TEKST             NVARCHAR2(500) NOT NULL,
    REDOSLED          NUMBER(10,0)   NOT NULL,
    DATUM_KREIRANJA   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE      TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANKETA_OPCIJE PRIMARY KEY (ID),
    CONSTRAINT FK_OPCIJE_PITANJE FOREIGN KEY (PITANJE_ID) REFERENCES PULS_ANKETA_PITANJA (ID),
    CONSTRAINT CK_OPCIJE_REDOSLED CHECK (REDOSLED > 0),
    CONSTRAINT UX_OPCIJE_REDOSLED UNIQUE (PITANJE_ID, REDOSLED)
);
CREATE INDEX IX_OPCIJE_PITANJE ON PULS_ANKETA_OPCIJE (PITANJE_ID);


-- ----------------------------------------------------------------------------
-- 6) PULS_ANKETA_USLOV_VREDNOSTI - vrednosti uslova zavisnog pitanja (1..n, ne CSV)
--    PITANJE_ID = zavisno pitanje ciji uslov ove vrednosti opisuju.
--    VREDNOST = kontrolisani string token (ID opcije / 'true'/'false' / broj ocene).
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_USLOV_VREDNOSTI (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    PITANJE_ID        NUMBER(19,0)   NOT NULL,
    VREDNOST          VARCHAR2(100)  NOT NULL,
    REDOSLED          NUMBER(10,0)   NOT NULL,
    CONSTRAINT PK_PULS_ANK_USLOV_VRED PRIMARY KEY (ID),
    CONSTRAINT FK_USLOV_VRED_PITANJE FOREIGN KEY (PITANJE_ID) REFERENCES PULS_ANKETA_PITANJA (ID),
    CONSTRAINT CK_USLOV_VRED_REDOSLED CHECK (REDOSLED > 0),
    CONSTRAINT UX_USLOV_VRED_REDOSLED UNIQUE (PITANJE_ID, REDOSLED),
    CONSTRAINT UX_USLOV_VRED_VREDNOST UNIQUE (PITANJE_ID, VREDNOST)
);
CREATE INDEX IX_USLOV_VRED_PITANJE ON PULS_ANKETA_USLOV_VREDNOSTI (PITANJE_ID);


-- ----------------------------------------------------------------------------
-- 7) PULS_ANKETA_CILJEVI - ciljne grupe ankete
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_CILJEVI (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    ANKETA_ID         NUMBER(19,0)   NOT NULL,
    TIP_CILJA         VARCHAR2(20)   NOT NULL,
    VREDNOST          VARCHAR2(100),
    DATUM_KREIRANJA   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE      TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANKETA_CILJEVI PRIMARY KEY (ID),
    CONSTRAINT FK_CILJEVI_ANKETA FOREIGN KEY (ANKETA_ID) REFERENCES PULS_ANKETE (ID),
    CONSTRAINT CK_CILJEVI_TIP
        CHECK (TIP_CILJA IN ('SVI', 'CENTRALA', 'MALOPRODAJA', 'ORGJED', 'PLATNI_BROJ')),
    -- SVI/CENTRALA/MALOPRODAJA nemaju vrednost; ORGJED/PLATNI_BROJ je zahtevaju.
    CONSTRAINT CK_CILJEVI_VREDNOST CHECK (
        (TIP_CILJA IN ('SVI', 'CENTRALA', 'MALOPRODAJA') AND VREDNOST IS NULL) OR
        (TIP_CILJA IN ('ORGJED', 'PLATNI_BROJ') AND VREDNOST IS NOT NULL))
);
-- Spreci dupliranje istog cilja po anketi (NVL resava nullable vrednost).
CREATE UNIQUE INDEX UX_CILJEVI_JEDINSTVEN
    ON PULS_ANKETA_CILJEVI (ANKETA_ID, TIP_CILJA, NVL(VREDNOST, '*'));
CREATE INDEX IX_CILJEVI_ANKETA ON PULS_ANKETA_CILJEVI (ANKETA_ID);


-- ----------------------------------------------------------------------------
-- 8) PULS_ANKETA_UCESCA - cinjenica da je korisnik dobio/zapoceo/predao anketu.
--    NEMA PREDAJA_ID (anonimnost) - vidi napomenu na kraju.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_UCESCA (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    ANKETA_ID         NUMBER(19,0)   NOT NULL,
    KORISNIK_ID       NUMBER(19,0)   NOT NULL,
    STATUS            VARCHAR2(20)   DEFAULT 'NOT_STARTED' NOT NULL,
    DATUM_POCETKA     TIMESTAMP(6),
    DATUM_PREDAJE     TIMESTAMP(6),
    DATUM_KREIRANJA   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE      TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANKETA_UCESCA PRIMARY KEY (ID),
    CONSTRAINT FK_UCESCA_ANKETA FOREIGN KEY (ANKETA_ID) REFERENCES PULS_ANKETE (ID),
    CONSTRAINT FK_UCESCA_KORISNIK FOREIGN KEY (KORISNIK_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT CK_UCESCA_STATUS CHECK (STATUS IN ('NOT_STARTED', 'IN_PROGRESS', 'SUBMITTED')),
    CONSTRAINT UX_UCESCA_ANKETA_KORISNIK UNIQUE (ANKETA_ID, KORISNIK_ID)
);
CREATE INDEX IX_UCESCA_ANKETA ON PULS_ANKETA_UCESCA (ANKETA_ID);
CREATE INDEX IX_UCESCA_KORISNIK ON PULS_ANKETA_UCESCA (KORISNIK_ID);


-- ----------------------------------------------------------------------------
-- 9) PULS_ANKETA_NACRT_ODGOVORI - privremeni odgovori (vezani za korisnika do predaje)
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_NACRT_ODGOVORI (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    ANKETA_ID         NUMBER(19,0)   NOT NULL,
    KORISNIK_ID       NUMBER(19,0)   NOT NULL,
    PITANJE_ID        NUMBER(19,0)   NOT NULL,
    TEKST             NCLOB,
    BROJ              NUMBER(10,0),
    LOGICKA           CHAR(1),
    DATUM_KREIRANJA   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE      TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANK_NACRT_ODG PRIMARY KEY (ID),
    CONSTRAINT FK_NACRT_ODG_ANKETA FOREIGN KEY (ANKETA_ID) REFERENCES PULS_ANKETE (ID),
    CONSTRAINT FK_NACRT_ODG_KORISNIK FOREIGN KEY (KORISNIK_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT FK_NACRT_ODG_PITANJE FOREIGN KEY (PITANJE_ID) REFERENCES PULS_ANKETA_PITANJA (ID),
    CONSTRAINT CK_NACRT_ODG_LOGICKA CHECK (LOGICKA IS NULL OR LOGICKA IN ('D', 'N')),
    CONSTRAINT UX_NACRT_ODG UNIQUE (ANKETA_ID, KORISNIK_ID, PITANJE_ID)
);
CREATE INDEX IX_NACRT_ODG_ANK_KOR ON PULS_ANKETA_NACRT_ODGOVORI (ANKETA_ID, KORISNIK_ID);


-- ----------------------------------------------------------------------------
-- 10) PULS_ANKETA_NACRT_OPCIJE - izabrane opcije nacrta (MULTI_CHOICE i dr.)
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_NACRT_OPCIJE (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    NACRT_ODGOVOR_ID  NUMBER(19,0)   NOT NULL,
    OPCIJA_ID         NUMBER(19,0)   NOT NULL,
    CONSTRAINT PK_PULS_ANK_NACRT_OPC PRIMARY KEY (ID),
    CONSTRAINT FK_NACRT_OPC_ODG FOREIGN KEY (NACRT_ODGOVOR_ID)
        REFERENCES PULS_ANKETA_NACRT_ODGOVORI (ID),
    CONSTRAINT FK_NACRT_OPC_OPCIJA FOREIGN KEY (OPCIJA_ID) REFERENCES PULS_ANKETA_OPCIJE (ID),
    CONSTRAINT UX_NACRT_OPC UNIQUE (NACRT_ODGOVOR_ID, OPCIJA_ID)
);
CREATE INDEX IX_NACRT_OPC_ODG ON PULS_ANKETA_NACRT_OPCIJE (NACRT_ODGOVOR_ID);


-- ----------------------------------------------------------------------------
-- 11) PULS_ANKETA_PREDAJE - finalna predaja (anonimna ili neanonimna, snapshot)
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_PREDAJE (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    ANKETA_ID         NUMBER(19,0)   NOT NULL,
    ANONIMNA          CHAR(1)        NOT NULL,
    KORISNIK_ID       NUMBER(19,0),
    -- Nullable: kod anonimne predaje DATUM_PREDAJE mora biti NULL da se predaja
    -- ne bi mogla povezati sa korisnikom preko preciznog timestamp-a.
    DATUM_PREDAJE     TIMESTAMP(6),
    CONSTRAINT PK_PULS_ANKETA_PREDAJE PRIMARY KEY (ID),
    CONSTRAINT FK_PREDAJE_ANKETA FOREIGN KEY (ANKETA_ID) REFERENCES PULS_ANKETE (ID),
    CONSTRAINT FK_PREDAJE_KORISNIK FOREIGN KEY (KORISNIK_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT CK_PREDAJE_ANONIMNA CHECK (ANONIMNA IN ('D', 'N')),
    -- Anonimna: KORISNIK_ID i DATUM_PREDAJE su NULL (nema veze ka korisniku ni preko
    -- vremena). Neanonimna: oba podatka postoje.
    CONSTRAINT CK_PREDAJE_ANON_KORISNIK CHECK (
        (ANONIMNA = 'D' AND KORISNIK_ID IS NULL AND DATUM_PREDAJE IS NULL) OR
        (ANONIMNA = 'N' AND KORISNIK_ID IS NOT NULL AND DATUM_PREDAJE IS NOT NULL))
);
-- Neanonimna: spreci dve predaje istog korisnika za istu anketu.
-- Anonimne predaje (KORISNIK_ID NULL) se NE indeksiraju (CASE -> NULL).
CREATE UNIQUE INDEX UX_PREDAJE_NEANON_KORISNIK ON PULS_ANKETA_PREDAJE (
    CASE WHEN KORISNIK_ID IS NOT NULL THEN ANKETA_ID END,
    CASE WHEN KORISNIK_ID IS NOT NULL THEN KORISNIK_ID END);
CREATE INDEX IX_PREDAJE_ANKETA ON PULS_ANKETA_PREDAJE (ANKETA_ID);


-- ----------------------------------------------------------------------------
-- 12) PULS_ANKETA_ODGOVORI - jedan finalni odgovor na jedno pitanje.
--     BEZ korisnik/platni broj kolone (anonimnost se stiti na nivou predaje).
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_ODGOVORI (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    PREDAJA_ID        NUMBER(19,0)   NOT NULL,
    PITANJE_ID        NUMBER(19,0)   NOT NULL,
    TEKST             NCLOB,
    BROJ              NUMBER(10,0),
    LOGICKA           CHAR(1),
    CONSTRAINT PK_PULS_ANKETA_ODGOVORI PRIMARY KEY (ID),
    CONSTRAINT FK_ODGOVORI_PREDAJA FOREIGN KEY (PREDAJA_ID) REFERENCES PULS_ANKETA_PREDAJE (ID),
    CONSTRAINT FK_ODGOVORI_PITANJE FOREIGN KEY (PITANJE_ID) REFERENCES PULS_ANKETA_PITANJA (ID),
    CONSTRAINT CK_ODGOVORI_LOGICKA CHECK (LOGICKA IS NULL OR LOGICKA IN ('D', 'N')),
    CONSTRAINT UX_ODGOVORI_PREDAJA_PIT UNIQUE (PREDAJA_ID, PITANJE_ID)
);
CREATE INDEX IX_ODGOVORI_PREDAJA ON PULS_ANKETA_ODGOVORI (PREDAJA_ID);
CREATE INDEX IX_ODGOVORI_PITANJE ON PULS_ANKETA_ODGOVORI (PITANJE_ID);


-- ----------------------------------------------------------------------------
-- 13) PULS_ANKETA_ODGOVOR_OPCIJE - izabrane opcije finalnog odgovora (1..n)
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ANKETA_ODGOVOR_OPCIJE (
    ID                NUMBER(19,0)   GENERATED BY DEFAULT AS IDENTITY,
    ODGOVOR_ID        NUMBER(19,0)   NOT NULL,
    OPCIJA_ID         NUMBER(19,0)   NOT NULL,
    CONSTRAINT PK_PULS_ANK_ODG_OPC PRIMARY KEY (ID),
    CONSTRAINT FK_ODG_OPC_ODGOVOR FOREIGN KEY (ODGOVOR_ID) REFERENCES PULS_ANKETA_ODGOVORI (ID),
    CONSTRAINT FK_ODG_OPC_OPCIJA FOREIGN KEY (OPCIJA_ID) REFERENCES PULS_ANKETA_OPCIJE (ID),
    CONSTRAINT UX_ODG_OPC UNIQUE (ODGOVOR_ID, OPCIJA_ID)
);
CREATE INDEX IX_ODG_OPC_ODGOVOR ON PULS_ANKETA_ODGOVOR_OPCIJE (ODGOVOR_ID);

COMMIT;