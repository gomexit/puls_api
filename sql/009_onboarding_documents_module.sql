-- ----------------------------------------------------------------------------
-- PULS_ONBOARDING_DOKUMENTI - jedan PDF dokument (DRAFT <-> PUBLISHED -> ARCHIVED)
--
-- Prelazi statusa (DRAFT -> PUBLISHED, DRAFT -> ARCHIVED, PUBLISHED -> DRAFT,
-- PUBLISHED -> ARCHIVED; ARCHIVED je terminalan) i pravilo "PDF se menja samo
-- dok je DRAFT" cuvaju se u servisnom sloju. U bazi su samo invarijante podataka.
-- Fizicko brisanje ne postoji.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_ONBOARDING_DOKUMENTI (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    NAZIV                   NVARCHAR2(200)  NOT NULL,
    OPIS                    NCLOB,
    ORIGINALNI_NAZIV_FAJLA  NVARCHAR2(255)  NOT NULL,
    MIME_TIP                VARCHAR2(100)   NOT NULL,
    VELICINA_BAJTOVA        NUMBER(12,0)    NOT NULL,
    SHA256                  CHAR(64)        NOT NULL,
    SADRZAJ                 BLOB            NOT NULL,
    STATUS                  VARCHAR2(20)    DEFAULT 'DRAFT' NOT NULL,
    REDOSLED                NUMBER(10,0)    DEFAULT 1 NOT NULL,
    VERZIJA                 NUMBER(10,0)    DEFAULT 1 NOT NULL,
    KREIRAO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    IZMENIO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE            TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_OBJAVE            TIMESTAMP(6),
    CONSTRAINT PK_PULS_ONB_DOKUMENTI PRIMARY KEY (ID),
    CONSTRAINT CK_ONB_DOK_STATUS
        CHECK (STATUS IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT CK_ONB_DOK_MIME
        CHECK (MIME_TIP = 'application/pdf'),
    CONSTRAINT CK_ONB_DOK_VELICINA
        CHECK (VELICINA_BAJTOVA > 0),
    CONSTRAINT CK_ONB_DOK_REDOSLED
        CHECK (REDOSLED > 0),
    CONSTRAINT CK_ONB_DOK_VERZIJA
        CHECK (VERZIJA > 0),
    CONSTRAINT CK_ONB_DOK_SHA256
        CHECK (LENGTH(SHA256) = 64),
    -- PUBLISHED uvek ima datum objave.
    CONSTRAINT CK_ONB_DOK_OBJAVA
        CHECK (STATUS <> 'PUBLISHED' OR DATUM_OBJAVE IS NOT NULL)
)
TABLESPACE GOMEX
LOB (SADRZAJ) STORE AS (TABLESPACE GOMEX)
LOB (OPIS) STORE AS (TABLESPACE GOMEX);

-- Employee lista (STATUS = 'PUBLISHED' ORDER BY REDOSLED, ID) i admin filtriranje.
CREATE INDEX IX_ONB_DOK_STATUS_RED
    ON PULS_ONBOARDING_DOKUMENTI (STATUS, REDOSLED, ID)
    TABLESPACE GOMEX;
