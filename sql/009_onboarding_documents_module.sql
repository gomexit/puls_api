-- Ovo NIJE modul automatskih onboarding anketa (sql/006_onboarding_surveys_module.sql).
-- Skripta ne dira nijednu postojecu tabelu.
--
-- Charset (potvrdjeno u prethodnim modulima):
--   NLS_CHARACTERSET       = EE8ISO8859P2  (NE cuva cirilicu/emoji u VARCHAR2!)
--   NLS_NCHAR_CHARACTERSET = AL16UTF16
-- Zato korisnicki tekst (NAZIV, OPIS, ORIGINALNI_NAZIV_FAJLA) ide u NVARCHAR2/NCLOB,
-- a kontrolisani kodovi (STATUS, MIME_TIP, SHA256, platni broj) ostaju VARCHAR2/CHAR.
--
-- PDF se cuva kao BLOB u samoj tabeli (bez javnih URL-ova i bez filesystem storage-a).
-- Lista dokumenata NIKADA ne cita SADRZAJ - aplikacija selektuje samo metadata kolone.
--
-- Skripta NE sadrzi: DROP / DELETE / TRUNCATE / ALTER postojecih tabela / seed podatke.
