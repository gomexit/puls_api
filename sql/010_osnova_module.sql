-- Charset (potvrdjeno u prethodnim modulima):
--   NLS_CHARACTERSET       = EE8ISO8859P2  (NE cuva cirilicu/emoji u VARCHAR2!)
--   NLS_NCHAR_CHARACTERSET = AL16UTF16
-- Korisnicki tekst (NAZIV, OPIS, ORIGINALNI_NAZIV_FAJLA) ide u NVARCHAR2.
--
-- Skripta NE sadrzi: DROP TABLE / DELETE / TRUNCATE / izmenu postojecih podataka.
-- Jedini ALTER-i su DROP+ADD CHECK ogranicenja koja se samo PROSIRUJU (isti obrazac
-- kao sql/005 i sql/006); svi postojeci redovi i dalje zadovoljavaju nova pravila.
-- HR izvori se ne citaju.
