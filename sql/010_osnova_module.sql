-- Sadrzaj:
--   1) PULS_SLIKE - nova tabela, slike (JPEG/PNG) kao BLOB, isto kao PDF dokumenti
--   2) PULS_OBAVESTENJA - kontrolisano PROSIRENJE CHECK ogranicenja za AKCIJA_TIP
--   3) PULS_SISTEMSKI_DOGADJAJI - kontrolisano PROSIRENJE CHECK ogranicenja za TIP
--   4) PULS_KONFIGURACIJA - novi kljucevi za ukljucivanje modula (samo ako ne postoje)
