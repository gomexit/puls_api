    'APP_VERSION_CHANGED',
    'ONBOARDING_SURVEY_AVAILABLE',
    'BENEFIT_PUBLISHED', 'HR_QUESTION_ANSWERED',
    'QUIZ_ACTIVATED', 'QUIZ_EXPIRING',
    'KUDOS_RECEIVED'));


