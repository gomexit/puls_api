-- ----------------------------------------------------------------------------
-- 1) PULS_SLIKE - jedna slika (logo partnera, slika pitanja u kvizu...)
--
-- Slika je nepromenljiva: posle upload-a se ne menja sadrzaj, samo STATUS
-- (AKTIVNA -> ARHIVIRANA). Backend proverava format, smanjuje sliku na najvise
-- 1200 px po duzoj strani i uklanja EXIF/GPS metapodatke PRE upisa, pa su
-- SIRINA, VISINA, VELICINA_BAJTOVA i SHA256 uvek vrednosti sacuvane slike.
-- Fizicko brisanje ne postoji.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_SLIKE (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    NAZIV                   NVARCHAR2(200)  NOT NULL,
    ORIGINALNI_NAZIV_FAJLA  NVARCHAR2(255)  NOT NULL,
    MIME_TIP                VARCHAR2(50)    NOT NULL,
    VELICINA_BAJTOVA        NUMBER(12,0)    NOT NULL,
    SIRINA                  NUMBER(5,0)     NOT NULL,
    VISINA                  NUMBER(5,0)     NOT NULL,
    SHA256                  CHAR(64)        NOT NULL,
    SADRZAJ                 BLOB            NOT NULL,
    STATUS                  VARCHAR2(20)    DEFAULT 'AKTIVNA' NOT NULL,
    KREIRAO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    IZMENIO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE            TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_SLIKE PRIMARY KEY (ID),
    CONSTRAINT CK_SLIKE_STATUS
        CHECK (STATUS IN ('AKTIVNA', 'ARHIVIRANA')),
    CONSTRAINT CK_SLIKE_MIME
        CHECK (MIME_TIP IN ('image/jpeg', 'image/png')),
    CONSTRAINT CK_SLIKE_VELICINA
        CHECK (VELICINA_BAJTOVA > 0),
    CONSTRAINT CK_SLIKE_DIMENZIJE
        CHECK (SIRINA BETWEEN 1 AND 1200 AND VISINA BETWEEN 1 AND 1200),
    CONSTRAINT CK_SLIKE_SHA256
        CHECK (LENGTH(SHA256) = 64)
)
TABLESPACE GOMEX
LOB (SADRZAJ) STORE AS (TABLESPACE GOMEX);

-- Admin lista (filter po statusu, najnovije prve).
CREATE INDEX IX_SLIKE_STATUS_DATUM
    ON PULS_SLIKE (STATUS, DATUM_KREIRANJA)
    TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 2) PULS_OBAVESTENJA - nove vrednosti AKCIJA_TIP za nove module
--
-- Klik na obavestenje u aplikaciji otvara pravi ekran:
--   BENEFIT     -> pogodnost        (RESURS_ID = PULS_POGODNOSTI.ID,      faza 1)
--   HR_QUESTION -> pitanje za HR    (RESURS_ID = PULS_HR_PITANJA.ID,      faza 2)
--   QUIZ        -> nedeljni kviz    (RESURS_ID = PULS_KVIZOVI.ID,         faza 3)
--   KUDOS       -> zahvalnica       (RESURS_ID = PULS_ZAHVALNICE.ID,      faza 4)
--   GAME        -> igra dana        (bez RESURS_ID; uvek dnevni nivo,     faza 5)
-- Tabele modula jos ne postoje, zato RESURS_ID namerno nema FK (isti obrazac
-- kao u sql/003 i sql/005). Postojece vrednosti ostaju; skup se samo prosiruje.
-- ----------------------------------------------------------------------------
ALTER TABLE PULS_OBAVESTENJA DROP CONSTRAINT CK_OBAV_AKCIJA_TIP;
ALTER TABLE PULS_OBAVESTENJA ADD CONSTRAINT CK_OBAV_AKCIJA_TIP
    CHECK (AKCIJA_TIP IN ('NONE', 'SURVEY', 'IDEA', 'URL', 'IDEA_CYCLE',
                          'BENEFIT', 'HR_QUESTION', 'QUIZ', 'KUDOS', 'GAME'));

ALTER TABLE PULS_OBAVESTENJA DROP CONSTRAINT CK_OBAV_AKCIJA_PODACI;
ALTER TABLE PULS_OBAVESTENJA ADD CONSTRAINT CK_OBAV_AKCIJA_PODACI CHECK (
    (AKCIJA_TIP IN ('NONE', 'GAME') AND RESURS_ID IS NULL AND AKCIJA_URL IS NULL) OR
    (AKCIJA_TIP IN ('SURVEY', 'IDEA', 'IDEA_CYCLE', 'BENEFIT', 'HR_QUESTION', 'QUIZ', 'KUDOS')
        AND RESURS_ID IS NOT NULL AND AKCIJA_URL IS NULL) OR
    (AKCIJA_TIP = 'URL' AND AKCIJA_URL IS NOT NULL AND RESURS_ID IS NULL));


-- ----------------------------------------------------------------------------
-- 3) PULS_SISTEMSKI_DOGADJAJI - novi tipovi dogadjaja za nove module
--
-- Postojeci tipovi (sql/005 + sql/006) se NE diraju; dodaju se:
--   BENEFIT_PUBLISHED, HR_QUESTION_ANSWERED, QUIZ_ACTIVATED, QUIZ_EXPIRING,
--   KUDOS_RECEIVED
