-- ============================================================================
-- 014_pitaj_hr_module.sql - modul PITAJ HR (privatna pitanja zaposlenih HR-u)
--
-- Preduslov: sql/010_osnova_module.sql (kljuc MODUL_PITAJ_HR, AKCIJA_TIP
-- 'HR_QUESTION', TIP_DOGADJAJA 'HR_QUESTION_ANSWERED').
-- Skripta je aditivna: samo nove tabele, indeksi i pocetne kategorije.
--
-- Tabele:
--   1) PULS_HR_KATEGORIJE     - sifarnik kategorija (uredjuje se u portalu)
--   2) PULS_HR_PITANJA        - pitanje zaposlenog (vide ga samo on i HR)
--   3) PULS_HR_PORUKE         - pitanje, odgovori HR-a i dopunsko pitanje
--   4) PULS_HR_CESTA_PITANJA  - "Cesta pitanja" koja HR objavljuje svima (bez imena)
--
-- Modul se ukljucuje parametrom MODUL_PITAJ_HR (ISKLJUCEN / PILOT / SVI).
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1) PULS_HR_KATEGORIJE - sifarnik kategorija pitanja
-- Brisanja nema: neaktivna kategorija ostaje na postojecim pitanjima, ali se ne
-- nudi za nova.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_HR_KATEGORIJE (
    SIFRA                   VARCHAR2(30)    NOT NULL,
    NAZIV                   NVARCHAR2(100)  NOT NULL,
    REDOSLED                NUMBER(5,0)     DEFAULT 0 NOT NULL,
    AKTIVNA                 CHAR(1)         DEFAULT 'D' NOT NULL,
    KREIRAO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    IZMENIO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE            TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_HR_KATEGORIJE PRIMARY KEY (SIFRA),
    CONSTRAINT CK_HR_KAT_AKTIVNA CHECK (AKTIVNA IN ('D', 'N')),
    CONSTRAINT CK_HR_KAT_SIFRA CHECK (REGEXP_LIKE(SIFRA, '^[A-Z0-9_]{1,30}$'))
)
TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 2) PULS_HR_PITANJA
-- STATUS: POSLATO (ceka odgovor HR-a), ODGOVORENO (HR je odgovorio; zaposleni
--         sme jednom da dopuni), ZATVORENO (nema vise poruka).
-- DOPUNA_POSLATA = 'D': zaposleni je iskoristio jedno dopunsko pitanje; sledeci
--         odgovor HR-a zatvara pitanje.
-- PROCITANO = 'N': postoji odgovor koji zaposleni jos nije otvorio (bedz).
-- ORGJED: snimak primarne org. jedinice u trenutku slanja (filter u portalu).
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_HR_PITANJA (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    KORISNIK_ID             NUMBER(19,0)    NOT NULL,
    KATEGORIJA_SIFRA        VARCHAR2(30)    NOT NULL,
    ORGJED                  VARCHAR2(50),
    STATUS                  VARCHAR2(20)    DEFAULT 'POSLATO' NOT NULL,
    DOPUNA_POSLATA          CHAR(1)         DEFAULT 'N' NOT NULL,
    PROCITANO               CHAR(1)         DEFAULT 'D' NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE            TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_ODGOVORA          TIMESTAMP(6),
    CONSTRAINT PK_PULS_HR_PITANJA PRIMARY KEY (ID),
    CONSTRAINT FK_HR_PIT_KORISNIK FOREIGN KEY (KORISNIK_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT FK_HR_PIT_KATEGORIJA FOREIGN KEY (KATEGORIJA_SIFRA) REFERENCES PULS_HR_KATEGORIJE (SIFRA),
    CONSTRAINT CK_HR_PIT_STATUS CHECK (STATUS IN ('POSLATO', 'ODGOVORENO', 'ZATVORENO')),
    CONSTRAINT CK_HR_PIT_DOPUNA CHECK (DOPUNA_POSLATA IN ('D', 'N')),
    CONSTRAINT CK_HR_PIT_PROCITANO CHECK (PROCITANO IN ('D', 'N'))
)
TABLESPACE GOMEX;

-- Moja pitanja, bedz neprocitanih odgovora i dnevno ogranicenje.
CREATE INDEX IX_HR_PIT_KORISNIK
    ON PULS_HR_PITANJA (KORISNIK_ID, DATUM_KREIRANJA)
    TABLESPACE GOMEX;

-- Lista u portalu po statusu (najstarije koje ceka prvo).
CREATE INDEX IX_HR_PIT_STATUS
    ON PULS_HR_PITANJA (STATUS, DATUM_IZMENE)
    TABLESPACE GOMEX;

CREATE INDEX IX_HR_PIT_KATEGORIJA
    ON PULS_HR_PITANJA (KATEGORIJA_SIFRA, STATUS)
    TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 3) PULS_HR_PORUKE - prepiska jednog pitanja, hronoloski
-- AUTOR: ZAPOSLENI (pitanje i dopuna) ili HR (odgovor). KORISNIK_ID je autor
-- poruke; aplikacija zaposlenom ne prikazuje ime HR-ovca.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_HR_PORUKE (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    PITANJE_ID              NUMBER(19,0)    NOT NULL,
    AUTOR                   VARCHAR2(20)    NOT NULL,
    KORISNIK_ID             NUMBER(19,0)    NOT NULL,
    TEKST                   NVARCHAR2(2000) NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_HR_PORUKE PRIMARY KEY (ID),
    CONSTRAINT FK_HR_POR_PITANJE FOREIGN KEY (PITANJE_ID) REFERENCES PULS_HR_PITANJA (ID),
    CONSTRAINT FK_HR_POR_KORISNIK FOREIGN KEY (KORISNIK_ID) REFERENCES PULS_KORISNICI (ID),
    CONSTRAINT CK_HR_POR_AUTOR CHECK (AUTOR IN ('ZAPOSLENI', 'HR'))
)
TABLESPACE GOMEX;

CREATE INDEX IX_HR_POR_PITANJE
    ON PULS_HR_PORUKE (PITANJE_ID, DATUM_KREIRANJA)
    TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 4) PULS_HR_CESTA_PITANJA - javni odgovori (bez imena onoga ko je pitao)
-- HR sam pise (ili prepravlja) tekst pre objave. IZVOR_PITANJE_ID je samo
-- informacija za portal i nikad se ne vraca aplikaciji.
-- ----------------------------------------------------------------------------
CREATE TABLE PULS_HR_CESTA_PITANJA (
    ID                      NUMBER(19,0)    GENERATED BY DEFAULT AS IDENTITY,
    KATEGORIJA_SIFRA        VARCHAR2(30)    NOT NULL,
    PITANJE                 NVARCHAR2(1000) NOT NULL,
    ODGOVOR                 NVARCHAR2(2000) NOT NULL,
    REDOSLED                NUMBER(5,0)     DEFAULT 0 NOT NULL,
    AKTIVNO                 CHAR(1)         DEFAULT 'D' NOT NULL,
    IZVOR_PITANJE_ID        NUMBER(19,0),
    KREIRAO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    IZMENIO_PLATNI_BROJ     VARCHAR2(30)    NOT NULL,
    DATUM_KREIRANJA         TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    DATUM_IZMENE            TIMESTAMP(6)    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PULS_HR_CESTA_PITANJA PRIMARY KEY (ID),
    CONSTRAINT FK_HR_CP_KATEGORIJA FOREIGN KEY (KATEGORIJA_SIFRA) REFERENCES PULS_HR_KATEGORIJE (SIFRA),
    CONSTRAINT FK_HR_CP_IZVOR FOREIGN KEY (IZVOR_PITANJE_ID) REFERENCES PULS_HR_PITANJA (ID),
    CONSTRAINT CK_HR_CP_AKTIVNO CHECK (AKTIVNO IN ('D', 'N'))
)
TABLESPACE GOMEX;

CREATE INDEX IX_HR_CP_AKTIVNO
    ON PULS_HR_CESTA_PITANJA (AKTIVNO, KATEGORIJA_SIFRA, REDOSLED)
    TABLESPACE GOMEX;


-- ----------------------------------------------------------------------------
-- 5) Pocetne kategorije (samo ako ne postoje; menjaju se kroz portal)
-- ----------------------------------------------------------------------------
MERGE INTO PULS_HR_KATEGORIJE k
USING (SELECT 'ODMOR' AS SIFRA, 'Godišnji odmor i odsustva' AS NAZIV, 10 AS REDOSLED FROM DUAL
       UNION ALL SELECT 'ZARADA', 'Zarada i obračun', 20 FROM DUAL
       UNION ALL SELECT 'BOLOVANJE', 'Bolovanje', 30 FROM DUAL
       UNION ALL SELECT 'UGOVOR', 'Ugovor i dokumenta', 40 FROM DUAL
       UNION ALL SELECT 'RASPORED', 'Raspored i smene', 50 FROM DUAL
       UNION ALL SELECT 'OSTALO', 'Ostalo', 90 FROM DUAL) src
   ON (k.SIFRA = src.SIFRA)
WHEN NOT MATCHED THEN
    INSERT (SIFRA, NAZIV, REDOSLED, AKTIVNA, KREIRAO_PLATNI_BROJ, IZMENIO_PLATNI_BROJ)
    VALUES (src.SIFRA, src.NAZIV, src.REDOSLED, 'D', 'SISTEM', 'SISTEM');

COMMIT;
